// ── Save articles ─────────────────────────────────────────────────────────────

function saveArticles(articles) {
  return db.transaction((items) => {
    let count = 0;
    for (const item of items) {
      if (insertArticle.run(item).changes > 0) count++;
    }
    return count;
  })(articles);
}

// ── FTS query sanitizer ───────────────────────────────────────────────────────

function toFTSQuery(q) {
  return q
    .replace(/[^\w\s]/g, " ")
    .trim()
    .split(/\s+/)
    .filter(Boolean)
    .join(" AND ");
}

// ── Get articles ──────────────────────────────────────────────────────────────

function getArticles({ category, language, search, hours, limit = 50, offset = 0 } = {}) {
  const params = [];
  const since = hours ? new Date(Date.now() - hours * 3600000).toISOString() : null;

  if (search) {
    const ftsQuery = toFTSQuery(search);
    if (!ftsQuery) return [];

    let query = `
      SELECT a.*
      FROM articles a
      JOIN articles_fts ON a.id = articles_fts.rowid
      WHERE articles_fts MATCH ?
    `;
    params.push(ftsQuery);

    if (since) {
      query += " AND a.pub_date >= ?";
      params.push(since);
    }
    if (category && category !== "all") {
      query += " AND a.category = ?";
      params.push(category);
    }
    if (language && language !== "all") {
      query += " AND a.language = ?";
      params.push(language);
    }

    query += " ORDER BY bm25(articles_fts), a.pub_date DESC";
    query += " LIMIT ? OFFSET ?";
    params.push(limit, offset);

    try {
      return db.prepare(query).all(...params);
    } catch {
      return [];
    }
  }

  // No search — use regular indexed query
  let query = `SELECT a.* FROM articles a WHERE 1=1`;

  if (since) {
    query += " AND a.pub_date >= ?";
    params.push(since);
  }
  if (category && category !== "all") {
    query += " AND a.category = ?";
    params.push(category);
  }
  if (language && language !== "all") {
    query += " AND a.language = ?";
    params.push(language);
  }

  query += " ORDER BY a.pub_date DESC, a.fetched_at DESC";
  query += " LIMIT ? OFFSET ?";
  params.push(limit, offset);

  return db.prepare(query).all(...params);
}

// ── Categories / Stats ────────────────────────────────────────────────────────

function getCategories() {
  return db.prepare("SELECT DISTINCT category FROM articles ORDER BY category").all().map((r) => r.category);
}

function getStats() {
  return {
    total: db.prepare("SELECT COUNT(*) as c FROM articles").get().c,
    byCategory: db.prepare("SELECT category, COUNT(*) as count FROM articles GROUP BY category ORDER BY count DESC").all(),
    byLanguage: db.prepare("SELECT language, COUNT(*) as count FROM articles GROUP BY language ORDER BY count DESC").all(),
    lastFetch: db.prepare("SELECT MAX(fetched_at) as last FROM articles").get().last,
  };
}

// ── Trending keywords ─────────────────────────────────────────────────────────

function getTrending(hours = 24, topN = 20) {
  const since = new Date(Date.now() - hours * 3600 * 1000).toISOString();
  const rows = db.prepare(
    "SELECT title, description FROM articles WHERE fetched_at >= ?"
  ).all(since);

  const freq = {};
  for (const row of rows) {
    const text = `${row.title || ""} ${row.description || ""}`;
    text
      .toLowerCase()
      .replace(/[^\w\s]/g, " ")
      .split(/\s+/)
      .forEach((w) => {
        if (w.length > 3 && !STOPWORDS.has(w) && !/^\d+$/.test(w)) {
          freq[w] = (freq[w] || 0) + 1;
        }
      });
  }

  return Object.entries(freq)
    .filter(([, count]) => count >= 3)
    .sort((a, b) => b[1] - a[1])
    .slice(0, topN)
    .map(([term, count]) => ({ term, count }));
}

// ── Related articles ──────────────────────────────────────────────────────────

function getRelated(articleId, limit = 5) {
  const article = db.prepare("SELECT id, title, description, category, language FROM articles WHERE id = ?").get(articleId);
  if (!article) return [];

  const text = `${article.title} ${article.description || ""}`;
  const seen = new Set();
  const keywords = [];
  for (const w of text.replace(/[^\w\s]/g, " ").split(/\s+/)) {
    const lower = w.toLowerCase();
    if (w.length > 3 && !STOPWORDS.has(lower) && !/^\d+$/.test(w) && !seen.has(lower)) {
      seen.add(lower);
      keywords.push(`"${w}"`);
    }
    if (keywords.length >= 8) break;
  }

  if (!keywords.length) return [];

  const andQuery = keywords.join(" AND ");
  const orQuery  = keywords.join(" OR ");

  try {
    const results = db.prepare(`
      SELECT a.* FROM articles a
      JOIN articles_fts ON a.id = articles_fts.rowid
      WHERE articles_fts MATCH ?
        AND a.id != ?
        AND a.language = ?
      ORDER BY bm25(articles_fts)
      LIMIT ?
    `).all(andQuery, articleId, article.language, limit);

    if (results.length >= limit) return results;

    const excludeIds = [articleId, ...results.map((r) => r.id)];
    const placeholders = excludeIds.map(() => "?").join(",");
    const extra = db.prepare(`
      SELECT a.* FROM articles a
      JOIN articles_fts ON a.id = articles_fts.rowid
      WHERE articles_fts MATCH ?
        AND a.id NOT IN (${placeholders})
        AND a.language = ?
        AND a.category = ?
      ORDER BY bm25(articles_fts)
      LIMIT ?
    `).all(orQuery, ...excludeIds, article.language, article.category, limit - results.length);

    return [...results, ...extra];
  } catch {
    return [];
  }
}

// ── Risk signals ──────────────────────────────────────────────────────────────

const insertRiskSignal = db.prepare(`
  INSERT OR REPLACE INTO risk_signals
    (guid, source, category, title, description, level, score, url, location, event_at)
  VALUES
    (@guid, @source, @category, @title, @description, @level, @score, @url, @location, @event_at)
`);

const upsertFetchLog = db.prepare(`
  INSERT OR REPLACE INTO risk_fetch_log (source, category, description, last_fetched_at, signal_count, last_error)
  VALUES (@source, @category, @description, @last_fetched_at, @signal_count, @last_error)
`);

function saveRiskSignals(signals, logEntries = []) {
  // Transaction 1: insert signals — individual failures are skipped, not fatal
  try {
    db.transaction(() => {
      for (const s of signals) {
        try { insertRiskSignal.run(s); } catch { /* skip invalid/duplicate signal */ }
      }
    })();
  } catch { /* ignore */ }

  // Transaction 2: update fetch log — ALWAYS runs, even if signal inserts failed
  const now = new Date().toISOString();
  try {
    db.transaction(() => {
      for (const e of logEntries) {
        upsertFetchLog.run({ last_error: null, ...e, last_fetched_at: now });
      }
    })();
  } catch { /* ignore */ }
}

function getRiskSignals(limit = 30) {
  let signals = [];
  let sources = [];

  try {
    signals = db.prepare(`
      SELECT * FROM risk_signals
      WHERE event_at >= datetime('now', '-72 hours')
         OR fetched_at >= datetime('now', '-24 hours')
      ORDER BY score DESC, event_at DESC
      LIMIT ?
    `).all(limit);
  } catch { /* risk_signals might not exist yet on first run */ }

  try {
    sources = db.prepare(
      "SELECT * FROM risk_fetch_log ORDER BY source ASC"
    ).all();
  } catch { /* risk_fetch_log might not exist yet */ }

  const lastFetch = sources.reduce((max, s) => {
    if (!s.last_fetched_at) return max;
    return !max || s.last_fetched_at > max ? s.last_fetched_at : max;
  }, null);

  return {
    signals,
    meta: { last_fetch: lastFetch, sources },
  };
}

